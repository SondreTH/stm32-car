int oled_text(int x, int y, const char *s, int scale) {
  if (scale < 1) scale = 1;
  for (; *s; s++) {
    unsigned char c = (unsigned char)*s;
    const uint8_t *g = font[(c >= ' ' && c <= '~') ? c - ' ' : '?' - ' '];
    for (int col = 0; col < 6; col++) {
      uint8_t bits = (col < 5) ? g[col] : 0;   /* 6th column = gap between letters */
      for (int row = 0; row < 8; row++)
        oled_fill(x + col * scale, y + row * scale, scale, scale, (bits >> row) & 1);
    }
    x += 6 * scale;
  }
  return x;
}

/* integer without printf (same reason as lb_int in car_comms.c) */
int oled_int(int x, int y, int32_t v, int scale) {
  char t[12];
  int n = sizeof t - 1;
  t[n] = 0;
  uint32_t u = (v < 0) ? (uint32_t)(-(int64_t)v) : (uint32_t)v;
  do { t[--n] = (char)('0' + u % 10); u /= 10; } while (u);
  if (v < 0) t[--n] = '-';
  return oled_text(x, y, &t[n], scale);
}
