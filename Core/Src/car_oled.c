/* =====================================================================
 * car_oled.c - I2C OLED: SSD1306 (0.96" / 0.91") or SH1106 (1.3")
 *
 * The display RAM is split into pages of 8 pixel rows. One byte is one
 * column of a page, bit 0 at the top. The framebuffer uses the same
 * layout, so oled_update() copies it out page by page. Page addressing
 * works the same on both controllers; SH1106 only needs a column offset.
 *
 * Every I2C write starts with a control byte: 0x00 = commands follow,
 * 0x40 = pixel data follows. HAL_I2C_Mem_Write() sends it as the
 * "memory address".
 * ===================================================================== */
#include "main.h"
#include "car_oled.h"
#include "car_config.h"
#include <string.h>

extern I2C_HandleTypeDef hi2c1;   /* PB8 SCL, PB9 SDA */

#define OLED_PAGES  (OLED_HEIGHT / 8)
#define I2C_TIMEOUT 10            /* ms per transfer; a 128-byte page takes ~3 ms at 400 kHz */

static uint8_t fb[OLED_PAGES][OLED_WIDTH];
static uint8_t addr = 0;          /* 7-bit I2C address, 0 = no display */

static bool send(uint8_t control, const uint8_t *d, uint16_t n) {
  return HAL_I2C_Mem_Write(&hi2c1, (uint16_t)(addr << 1), control, I2C_MEMADD_SIZE_8BIT,
                           (uint8_t *)d, n, I2C_TIMEOUT) == HAL_OK;
}

/* ------------------------------------------------------------------ init */
static const uint8_t initCmds[] = {
  0xAE,                                   /* display off while setting up       */
  0xD5, 0x80,                             /* clock divider / oscillator         */
  0xA8, OLED_HEIGHT - 1,                  /* multiplex: number of rows - 1      */
  0xD3, 0x00,                             /* no vertical offset                 */
  0x40,                                   /* start at RAM row 0                 */
  0x8D, 0x14,                             /* SSD1306 charge pump on (SH1106: no-op) */
  0x20, 0x02,                             /* page addressing mode               */
  OLED_FLIP ? 0xA0 : 0xA1,                /* column order                       */
  OLED_FLIP ? 0xC0 : 0xC8,                /* row order                          */
  0xDA, OLED_HEIGHT == 64 ? 0x12 : 0x02,  /* COM pin layout of the panel        */
  0x81, 0xCF,                             /* contrast 0..255                    */
  0xD9, 0xF1,                             /* pre-charge period                  */
  0xDB, 0x40,                             /* VCOMH level                        */
  0xA4,                                   /* show RAM contents                  */
  0xA6,                                   /* normal, not inverted               */
};

uint8_t oled_init(void) {
  addr = 0;
  for (uint8_t a = 0x3C; a <= 0x3D && !addr; a++)
    if (HAL_I2C_IsDeviceReady(&hi2c1, (uint16_t)(a << 1), 2, I2C_TIMEOUT) == HAL_OK) addr = a;
  if (!addr) return 0;

  static const uint8_t displayOn = 0xAF;
  if (!send(0x00, initCmds, sizeof initCmds)) { addr = 0; return 0; }
  oled_clear();
  if (!oled_update()) return 0;            /* clear the RAM before switching on */
  if (!send(0x00, &displayOn, 1)) { addr = 0; return 0; }
  return addr;
}

bool oled_update(void) {
  if (!addr) return false;
  for (uint8_t p = 0; p < OLED_PAGES; p++) {
    const uint8_t at[3] = { (uint8_t)(0xB0 | p),                       /* page p           */
                            (uint8_t)(0x00 | (OLED_COL_OFFSET & 0x0F)), /* column, low bits */
                            (uint8_t)(0x10 | (OLED_COL_OFFSET >> 4)) }; /* column, high bits */
    if (!send(0x00, at, 3) || !send(0x40, fb[p], OLED_WIDTH)) {
      addr = 0;                            /* lost it: stop until oled_init() again */
      return false;
    }
  }
  return true;
}

/* --------------------------------------------------------------- drawing */
void oled_clear(void) { memset(fb, 0, sizeof fb); }

void oled_pixel(int x, int y, bool on) {
  if (x < 0 || x >= OLED_WIDTH || y < 0 || y >= OLED_HEIGHT) return;
  uint8_t bit = (uint8_t)(1u << (y & 7));
  if (on) fb[y >> 3][x] |= bit; else fb[y >> 3][x] &= (uint8_t)~bit;
}

void oled_fill(int x, int y, int w, int h, bool on) {
  for (int j = y; j < y + h; j++)
    for (int i = x; i < x + w; i++) oled_pixel(i, j, on);
}

void oled_frame(int x, int y, int w, int h) {
  oled_fill(x, y, w, 1, true);  oled_fill(x, y + h - 1, w, 1, true);
  oled_fill(x, y, 1, h, true);  oled_fill(x + w - 1, y, 1, h, true);
}

